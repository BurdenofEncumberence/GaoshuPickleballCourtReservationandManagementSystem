            fputcsv($handle, ['--- ITEMIZED PAYMENT LEDGER ---']);
            fputcsv($handle, [
                'Payment ID',
                'Payment Reference / Session',
                'Booking Reference',
                'Transaction Date',
                'Customer Name',

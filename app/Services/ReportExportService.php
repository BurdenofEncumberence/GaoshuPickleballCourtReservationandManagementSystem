                'Average Paid Transaction Value',
                $paidCount > 0 ? number_format($totalPaidAmount / $paidCount, 2, '.', '') : '0.00',
                '-',
            ]);
            fputcsv($handle, []);

            // Payment Methods Breakdown
            fputcsv($handle, ['--- PAYMENT METHOD BREAKDOWN ---']);
            fputcsv($handle, ['Payment Method', 'Total Collections (PHP)', 'Transaction Count', 'Share (%)']);
            foreach ($methodBreakdown as $method => $data) {
                fputcsv($handle, [
                    ucfirst((string) $method),
                    number_format($data['total'], 2, '.', ''),
                    $data['count'],
                    $data['percent'] . '%',

    public const DAILY_OPERATING_HOURS = 16;

    /**
     * Resolve date range parameters for the given period identifier.
     */
    public function resolveDateRange(string $period): array
    {
        $now = Carbon::now();

        return match ($period) {
            'this_day', 'today' => [
                'start' => Carbon::today()->startOfDay(),
                'end' => Carbon::today()->endOfDay(),
                'label' => 'This Day (' . Carbon::today()->format('Y-m-d') . ')',
                'period_key' => 'this_day',
                'days' => 1,
            ],
            'last_month' => [
                'start' => $now->copy()->subMonth()->startOfMonth()->startOfDay(),
                'end' => $now->copy()->subMonth()->endOfMonth()->endOfDay(),
                'label' => 'Last Month (' . $now->copy()->subMonth()->format('F Y') . ')',
                'period_key' => 'last_month',
                'days' => $now->copy()->subMonth()->daysInMonth,
            ],
            'this_year' => [
                'start' => $now->copy()->startOfYear()->startOfDay(),
                'end' => $now->copy()->endOfYear()->endOfDay(),
                'label' => 'This Year (' . $now->year . ')',
                'period_key' => 'this_year',
                'days' => $now->isLeapYear() ? 366 : 365,
            ],
            default => [
                'start' => $now->copy()->startOfMonth()->startOfDay(),
                'end' => $now->copy()->endOfMonth()->endOfDay(),
                'label' => 'This Month (' . $now->format('F Y') . ')',
                'period_key' => 'this_month',
                'days' => $now->daysInMonth,
            ],
        };
    }

    /**
     * Export Overall Operations Report.
     */
    public function exportOverall(string $period, User $user): StreamedResponse
    {
        $range = $this->resolveDateRange($period);
        $startDate = $range['start']->toDateString();
        $endDate = $range['end']->toDateString();

        $bookings = Booking::with(['court', 'user', 'payments.processor', 'statusUpdatedBy'])
            ->whereBetween('date', [$startDate, $endDate])
            ->orderBy('date')
            ->orderBy('start_time')
            ->get();

        $payments = Payment::whereBetween('date', [$startDate, $endDate])->get();
        $paidPayments = $payments->where('payment_status', 'paid');

        $totalRevenue = (float) $paidPayments->sum('amount');
        $onlineRevenue = (float) $paidPayments->where('payment_method', 'paymongo')->sum('amount');
        $cashRevenue = (float) $paidPayments->where('payment_method', 'cash')->sum('amount');

        $activeBookings = $bookings->where('booking_status', '!=', 'cancelled');
        $bookedHours = (float) $activeBookings->sum(fn ($b) => $this->calculateBookingHours($b));

        $availableCourtsCount = max(Court::where('court_status', 'available')->count(), 1);
        $capacityHours = $availableCourtsCount * self::DAILY_OPERATING_HOURS * $range['days'];
        $utilizationRate = $capacityHours > 0 ? min(round(($bookedHours / $capacityHours) * 100, 1), 100.0) : 0.0;

        $filename = 'overall-report-' . $range['period_key'] . '-' . date('Y-m-d') . '.csv';

        return response()->streamDownload(function () use ($range, $user, $bookings, $activeBookings, $totalRevenue, $onlineRevenue, $cashRevenue, $bookedHours, $capacityHours, $utilizationRate) {
            $handle = fopen('php://output', 'w');
            // Write UTF-8 BOM for Excel compatibility
            fwrite($handle, "\xEF\xBB\xBF");

            $siteName = SiteSettings::first()->system_name ?? 'Gaoshou Pickleball';

            fputcsv($handle, [$siteName . ' - OVERALL OPERATIONS REPORT']);
            fputcsv($handle, ['Reporting Period', $range['label']]);
            fputcsv($handle, ['Generated At', Carbon::now()->toDateTimeString()]);
            fputcsv($handle, ['Generated By', $user->name . ' (' . strtoupper($user->role) . ')']);
            fputcsv($handle, []);

            // KPI Executive Summary
            fputcsv($handle, ['--- EXECUTIVE SUMMARY METRICS ---']);
            fputcsv($handle, ['Metric', 'Value']);
            fputcsv($handle, ['Total Bookings Logged', $bookings->count()]);
            fputcsv($handle, ['Confirmed / Active Bookings', $bookings->whereIn('booking_status', ['confirmed', 'show'])->count()]);
            fputcsv($handle, ['Pending Bookings', $bookings->where('booking_status', 'pending')->count()]);
            fputcsv($handle, ['Cancelled Bookings', $bookings->where('booking_status', 'cancelled')->count()]);
            fputcsv($handle, ['No-Show Bookings', $bookings->where('booking_status', 'no_show')->count()]);
            fputcsv($handle, ['Online Bookings', $bookings->where('booking_type', 'online')->count()]);
            fputcsv($handle, ['Walk-In Bookings', $bookings->where('booking_type', 'walk_in')->count()]);
            fputcsv($handle, ['Total Collected Revenue (PHP)', number_format($totalRevenue, 2, '.', '')]);
            fputcsv($handle, ['Online Revenue (PHP)', number_format($onlineRevenue, 2, '.', '')]);
            fputcsv($handle, ['Cash / Counter Revenue (PHP)', number_format($cashRevenue, 2, '.', '')]);
            fputcsv($handle, ['Total Court Hours Booked', number_format($bookedHours, 2, '.', '')]);
            fputcsv($handle, ['Facility Capacity Hours', $capacityHours]);
            fputcsv($handle, ['Facility Utilization Rate (%)', $utilizationRate . '%']);
            fputcsv($handle, []);

            // Detailed Bookings Table
            fputcsv($handle, ['--- ITEMIZED BOOKINGS LIST ---']);
            fputcsv($handle, [
                'Booking ID',
                'Reference Number',
                'Customer Name',
                'Customer Email',
                'Court Name',
                'Date',
                'Start Time',
                'End Time',
                'Duration (Hours)',
                'Booking Type',
                'Booking Status',
                'Cashier / Processed By',
                'Attendance Marked By',
                'Attendance Marked At',
                'Amount (PHP)',
                'Payment Method',
                'Payment Status',
            ]);

            foreach ($bookings as $booking) {
                $payment = $booking->payments->first();
                $hours = $this->calculateBookingHours($booking);

                fputcsv($handle, [
                    $booking->id,
                    $booking->reference_number ?? ('BK-' . $booking->id),
                    $booking->user->name ?? $booking->customer_name ?? 'Guest Customer',
                    $booking->user->email ?? $booking->customer_email ?? 'N/A',
                    $booking->court->court_name ?? 'Court #' . $booking->court_id,
                    $booking->date,
                    $booking->start_time,
                    $booking->end_time,
                    number_format($hours, 2, '.', ''),
                    ucfirst(str_replace('_', ' ', $booking->booking_type ?? 'online')),
                    ucfirst($booking->booking_status),
                    $payment?->processor?->name ?? ($booking->isWalkIn() ? 'Walk-In Desk' : 'Online Gateway'),
                    $booking->statusUpdatedBy?->name ?? 'Unmarked',
                    $booking->status_updated_at ? $booking->status_updated_at->toDateTimeString() : 'N/A',
                    $payment ? number_format((float) $payment->amount, 2, '.', '') : '0.00',
                    $payment ? ucfirst($payment->payment_method) : 'N/A',
                    $payment ? ucfirst($payment->payment_status) : 'N/A',
                ]);
            }

            fclose($handle);
        }, $filename, [
            'Content-Type' => 'text/csv; charset=UTF-8',
            'Content-Disposition' => "attachment; filename=\"{$filename}\"",
        ]);
    }

    /**
     * Export Financial and Revenue Audit Report.
     */
    public function exportFinancial(string $period, User $user): StreamedResponse
    {
        $range = $this->resolveDateRange($period);
        $startDate = $range['start']->toDateString();
        $endDate = $range['end']->toDateString();

        $payments = Payment::with(['booking.court', 'booking.user', 'processor', 'booking.statusUpdatedBy'])
            ->whereBetween('date', [$startDate, $endDate])
            ->orderBy('date')
            ->orderBy('created_at')
            ->get();

        $paidPayments = $payments->where('payment_status', 'paid');
        $totalPaidAmount = (float) $paidPayments->sum('amount');
        $paidCount = $paidPayments->count();
        $pendingPayments = $payments->where('payment_status', 'pending');
        $pendingCount = $pendingPayments->count();
        $pendingAmount = (float) $pendingPayments->sum('amount');

        $onlinePaid = $paidPayments->filter(fn ($p) => ($p->booking->booking_type ?? '') === 'online');
        $walkInPaid = $paidPayments->filter(fn ($p) => ($p->booking->booking_type ?? '') === 'walk_in');

        $methodBreakdown = $paidPayments->groupBy('payment_method')->map(function ($group) use ($totalPaidAmount) {
            $sum = (float) $group->sum('amount');
            return [
                'total' => $sum,
                'count' => $group->count(),
                'percent' => $totalPaidAmount > 0 ? round(($sum / $totalPaidAmount) * 100, 1) : 0.0,
            ];
        });

        $filename = 'financial-report-' . $range['period_key'] . '-' . date('Y-m-d') . '.csv';

        return response()->streamDownload(function () use ($range, $user, $payments, $totalPaidAmount, $paidCount, $pendingCount, $pendingAmount, $onlinePaid, $walkInPaid, $methodBreakdown) {
            $handle = fopen('php://output', 'w');

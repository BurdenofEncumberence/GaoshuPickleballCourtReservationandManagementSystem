    /**
     * Export Court Capacity and Utilization Report.
     */
    public function exportUtilization(string $period, User $user): StreamedResponse
    {
        $range = $this->resolveDateRange($period);
        $startDate = $range['start']->toDateString();
        $endDate = $range['end']->toDateString();

        $courts = Court::with(['bookings' => function ($q) use ($startDate, $endDate) {
            $q->where('booking_status', '!=', 'cancelled')
                ->whereBetween('date', [$startDate, $endDate])
                ->with('payments');
        }])->orderBy('court_name')->get();

        $days = $range['days'];
        $courtCapacity = self::DAILY_OPERATING_HOURS * $days;
        $totalCourts = $courts->count();
        $availableCourts = $courts->where('court_status', 'available')->count();
        $totalFacilityCapacity = max($availableCourts, 1) * $courtCapacity;

        $courtStats = $courts->map(function (Court $court) use ($courtCapacity) {
            $bookings = $court->bookings;
            $bookedHours = (float) $bookings->sum(fn ($b) => $this->calculateBookingHours($b));
            $rate = $courtCapacity > 0 ? min(round(($bookedHours / $courtCapacity) * 100, 1), 100.0) : 0.0;
            $revenue = (float) $bookings->flatMap->payments->where('payment_status', 'paid')->sum('amount');
            $revPach = $courtCapacity > 0 ? round($revenue / $courtCapacity, 2) : 0.0;
            $peakSlot = $this->determinePeakSlot($bookings);

            return [
                'court' => $court,
                'capacity_hours' => $courtCapacity,
                'booked_hours' => $bookedHours,
                'utilization_rate' => $rate,
                'sessions_count' => $bookings->count(),
                'revenue' => $revenue,
                'rev_pach' => $revPach,
                'peak_slot' => $peakSlot,
            ];
        });

        $totalFacilityBookedHours = (float) $courtStats->sum('booked_hours');
        $facilityUtilizationRate = $totalFacilityCapacity > 0
            ? min(round(($totalFacilityBookedHours / $totalFacilityCapacity) * 100, 1), 100.0)
            : 0.0;
        $totalFacilityRevenue = (float) $courtStats->sum('revenue');

        $filename = 'utilization-report-' . $range['period_key'] . '-' . date('Y-m-d') . '.csv';

        return response()->streamDownload(function () use ($range, $user, $courts, $courtStats, $days, $totalCourts, $availableCourts, $totalFacilityCapacity, $totalFacilityBookedHours, $facilityUtilizationRate, $totalFacilityRevenue) {
            $handle = fopen('php://output', 'w');
            fwrite($handle, "\xEF\xBB\xBF");

            $siteName = SiteSettings::first()->system_name ?? 'Gaoshou Pickleball';

            fputcsv($handle, [$siteName . ' - COURT UTILIZATION & CAPACITY REPORT']);
            fputcsv($handle, ['Reporting Period', $range['label']]);
            fputcsv($handle, ['Days in Period', $days]);
            fputcsv($handle, ['Generated At', Carbon::now()->toDateTimeString()]);
            fputcsv($handle, ['Generated By', $user->name . ' (' . strtoupper($user->role) . ')']);
            fputcsv($handle, []);

            // Facility Summary
            fputcsv($handle, ['--- FACILITY CAPACITY METRICS ---']);
            fputcsv($handle, ['Metric', 'Value']);
            fputcsv($handle, ['Total Courts in Facility', $totalCourts]);
            fputcsv($handle, ['Available Operating Courts', $availableCourts]);
            fputcsv($handle, ['Daily Operating Hours Per Court', self::DAILY_OPERATING_HOURS . ' Hours (6:00 AM - 10:00 PM)']);
            fputcsv($handle, ['Total Facility Capacity Hours', $totalFacilityCapacity . ' Hours']);
            fputcsv($handle, ['Total Hours Booked / Utilized', number_format($totalFacilityBookedHours, 2, '.', '') . ' Hours']);
            fputcsv($handle, ['Facility Utilization Rate (%)', $facilityUtilizationRate . '%']);
            fputcsv($handle, ['Total Revenue Generated by Fleet (PHP)', number_format($totalFacilityRevenue, 2, '.', '')]);
            fputcsv($handle, [
                'Facility RevPACH (Revenue Per Available Court Hour)',
                $totalFacilityCapacity > 0 ? 'PHP ' . number_format($totalFacilityRevenue / $totalFacilityCapacity, 2, '.', '') : 'PHP 0.00',
            ]);
            fputcsv($handle, []);

            // Per Court Breakdown
            fputcsv($handle, ['--- PER-COURT UTILIZATION BREAKDOWN ---']);
            fputcsv($handle, [
                'Court ID',
                'Court Name',
                'Status',
                'Hourly Rate (PHP)',
                'Operating Capacity (Hours)',
                'Actual Booked Hours',
                'Utilization Rate (%)',
                'Sessions Count',
                'Revenue Generated (PHP)',
                'RevPACH (PHP/Hour)',
                'Peak Time Slot',
            ]);

            foreach ($courtStats as $stat) {
                $court = $stat['court'];
                fputcsv($handle, [
                    $court->id,
                    $court->court_name,
                    ucfirst($court->court_status),
                    number_format((float) $court->price_per_hour, 2, '.', ''),
                    $stat['capacity_hours'],
                    number_format($stat['booked_hours'], 2, '.', ''),
                    $stat['utilization_rate'] . '%',
                    $stat['sessions_count'],
                    number_format($stat['revenue'], 2, '.', ''),
                    number_format($stat['rev_pach'], 2, '.', ''),
                    $stat['peak_slot'],
                ]);
            }
            fputcsv($handle, []);

            // Itemized Slot Utilizations
            fputcsv($handle, ['--- ITEMIZED COURT BOOKING SESSIONS ---']);
            fputcsv($handle, [
                'Date',
                'Court Name',
                'Start Time',
                'End Time',
                'Duration (Hours)',
                'Booking Reference',
                'Customer Name',
                'Booking Type',
                'Attendance Status',
            ]);

            foreach ($courts as $court) {
                foreach ($court->bookings as $booking) {
                    $hours = $this->calculateBookingHours($booking);
                    fputcsv($handle, [
                        $booking->date,
                        $court->court_name,
                        $booking->start_time,
                        $booking->end_time,
                        number_format($hours, 2, '.', ''),
                        $booking->reference_number ?? ('BK-' . $booking->id),
                        $booking->user->name ?? $booking->customer_name ?? 'Guest Customer',
                        ucfirst(str_replace('_', ' ', $booking->booking_type ?? 'online')),
                        ucfirst($booking->booking_status),
                    ]);
                }
            }

            fclose($handle);
        }, $filename, [
            'Content-Type' => 'text/csv; charset=UTF-8',
            'Content-Disposition' => "attachment; filename=\"{$filename}\"",
        ]);
    }

    /**
     * Calculate booking duration in hours.
     */
    public function calculateBookingHours(Booking $booking): float
    {
        if (empty($booking->start_time) || empty($booking->end_time)) {
            return 1.0;
        }

        try {
            $start = Carbon::parse($booking->start_time);
            $end = Carbon::parse($booking->end_time);
            $diffMins = abs($start->diffInMinutes($end));
            return $diffMins > 0 ? round($diffMins / 60, 2) : 1.0;
        } catch (\Throwable $e) {
            return 1.0;
        }
    }

    /**
     * Determine the peak time slot.
     */
    protected function determinePeakSlot($bookings): string
    {
        if ($bookings->isEmpty()) {
            return 'N/A';
        }

        $frequencies = [];
        foreach ($bookings as $b) {
            if (empty($b->start_time) || empty($b->end_time)) {
                continue;
            }
            try {
                $start = Carbon::parse($b->start_time)->format('g:i A');
                $end = Carbon::parse($b->end_time)->format('g:i A');
                $slotKey = "{$start} - {$end}";
                $frequencies[$slotKey] = ($frequencies[$slotKey] ?? 0) + 1;
            } catch (\Throwable $e) {
                continue;
            }
        }

        if (empty($frequencies)) {
            return 'N/A';
        }

        arsort($frequencies);
        return array_key_first($frequencies);
    }

